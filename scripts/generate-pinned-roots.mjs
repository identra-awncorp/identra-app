// Regenerates src/native/domain/wallet/pinnedRoots.ts from the Root CA certificate(s) the website
// publishes (ADR-0015 §8: during a rollover, pass the old and the new root).
// Usage: node scripts/generate-pinned-roots.mjs ../identra-website/src/identra/trust/root-ca.pem [more.pem]
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';

const files = process.argv.slice(2);
if (files.length === 0) throw new Error('give at least one PEM file');
const roots = files.flatMap((file) =>
  [...readFileSync(file, 'utf8').matchAll(/-----BEGIN CERTIFICATE-----([\s\S]+?)-----END CERTIFICATE-----/g)].map((m) => m[1].replace(/\s+/g, '')),
);
const lines = roots.map((b64) => {
  const fp = createHash('sha256').update(Buffer.from(b64, 'base64')).digest('hex').toUpperCase().match(/../g).join(':');
  return `  // SHA-256 ${fp}\n  '${b64}',`;
});
writeFileSync(
  new URL('../src/native/domain/wallet/pinnedRoots.ts', import.meta.url),
  `// Generated by scripts/generate-pinned-roots.mjs from identra-website/src/identra/trust/root-ca.pem.
// The Identra Root CA certificate(s) the wallet trusts, base64 DER. An array so a second root can be
// pinned during a rollover (ADR-0015 §8). Public certificates, not secrets.
export const PINNED_ROOT_CERTIFICATES_BASE64: readonly string[] = [
${lines.join('\n')}
];
`,
);
console.log(`pinned ${roots.length} root(s)`);
