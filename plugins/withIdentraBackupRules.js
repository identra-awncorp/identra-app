// Android Auto Backup rules for the wallet (ADR-0009 §5). Only what is listed with <include> is
// backed up, so everything else stays out: the wallet database (files/SQLite/identra-wallet.db),
// AsyncStorage (databases/), the SecureStore shared preferences that hold the encrypted wallet
// keys and data key (excluded explicitly), and Android Keystore keys (never in any backup).
// In: the backup catalogue (document type and issuer only) and the remaining shared preferences,
// which is what expo-secure-store's own rules backed up before (its rules are switched off in
// app.json so these are the only ones).
const fs = require('fs');
const path = require('path');
const { AndroidConfig, withAndroidManifest, withDangerousMod } = require('expo/config-plugins');

// Same name as CATALOGUE_FILE_NAME in src/native/domain/wallet/walletContainer.ts (a test checks it).
const CATALOGUE_FILE_NAME = 'identra-backup-catalogue.json';
const BACKUP_RULES = 'identra_backup_rules';
const EXTRACTION_RULES = 'identra_data_extraction_rules';

const rules = `    <include domain="file" path="${CATALOGUE_FILE_NAME}" />
    <include domain="sharedpref" path="." />
    <exclude domain="sharedpref" path="SecureStore.xml" />`;

// Android 12+ (API 31+): cloud backup and device-to-device transfer.
const dataExtractionRulesXml = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/withIdentraBackupRules.js. Not included = not backed up. -->
<data-extraction-rules>
  <cloud-backup>
${rules}
  </cloud-backup>
  <device-transfer>
${rules}
  </device-transfer>
</data-extraction-rules>
`;

// Android 11 and lower.
const fullBackupContentXml = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/withIdentraBackupRules.js. Not included = not backed up. -->
<full-backup-content>
${rules.replace(/^ {4}/gm, '  ')}
</full-backup-content>
`;

function withIdentraBackupRules(config) {
  config = withAndroidManifest(config, (cfg) => {
    const application = AndroidConfig.Manifest.getMainApplicationOrThrow(cfg.modResults);
    application.$['android:allowBackup'] = 'true';
    application.$['android:fullBackupContent'] = `@xml/${BACKUP_RULES}`;
    application.$['android:dataExtractionRules'] = `@xml/${EXTRACTION_RULES}`;
    return cfg;
  });
  return withDangerousMod(config, [
    'android',
    async (cfg) => {
      const dir = path.join(cfg.modRequest.platformProjectRoot, 'app', 'src', 'main', 'res', 'xml');
      await fs.promises.mkdir(dir, { recursive: true });
      await fs.promises.writeFile(path.join(dir, `${BACKUP_RULES}.xml`), fullBackupContentXml);
      await fs.promises.writeFile(path.join(dir, `${EXTRACTION_RULES}.xml`), dataExtractionRulesXml);
      return cfg;
    },
  ]);
}

module.exports = withIdentraBackupRules;
module.exports.CATALOGUE_FILE_NAME = CATALOGUE_FILE_NAME;
module.exports.dataExtractionRulesXml = dataExtractionRulesXml;
module.exports.fullBackupContentXml = fullBackupContentXml;
